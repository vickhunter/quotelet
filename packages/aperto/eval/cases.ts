// mentioned, minimum = max(min, ...)). Prices are invented for testing, not market data.
import type { Answers, Config, Field } from "../../core/src/index.ts";
import type { Lang } from "../src/types.ts";

export type EvalCase = { id: string; lang: Lang; text: string; gold: Config; inputs: Answers[]; ambiguous?: boolean; note?: string };

const num = (id: string, label: string, min: number, max: number, def: number, unit?: string): Field => ({ id, type: "number", label, ...(unit ? { unit } : {}), min, max, step: 1, default: def });
const tog = (id: string, label: string, on: number, off: number): Field => ({ id, type: "toggle", label, on, off, default: false });
const cho = (id: string, label: string, opts: [string, number][]): Field => ({ id, type: "choice", label, options: opts.map(([l, v]) => ({ label: l, value: v })), default: 0 });
type Vat = Config["vat"];
const vatIn = (rate: number): Vat => ({ rate, pricesInclude: true, show: true });
const vatEx = (rate: number): Vat => ({ rate, pricesInclude: false, show: true });

function cfg(id: string, locale: string, currency: string, title: string, business: string, fields: Field[], formula: string, extra: Partial<Config> = {}): Config {
  return { v: 1, id, locale, currency, title, business: { name: business }, fields, formula, range: { low: 0.9, high: 1.1 }, rounding: 10, ...extra, branding: true } as Config;
}

